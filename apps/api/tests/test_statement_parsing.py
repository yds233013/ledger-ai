"""Reading transaction tables out of statement PDFs.

Every fixture is generated by `tests.synthetic_pdf`, never collected. The
guard test at the bottom asserts that, so a real statement cannot enter the
suite by accident.

The cases that matter most are the ones where being wrong is invisible: a
continuation page silently dropped makes a short month look like a complete
one, and a sign taken on trust turns a payment into income.
"""

from __future__ import annotations

from datetime import date

import pypdfium2 as pdfium
import pytest

from ledgerai.security.validators import ValidationError
from ledgerai.services.statements import extract_pages, parse_statement, verify_text_layer
from ledgerai.services.statements.extract import NoTextLayerError
from ledgerai.services.statements.layout import (
    group_lines,
    infer_columns,
    looks_like_amount,
    looks_like_date,
)
from ledgerai.services.statements.parse import parse_amount, parse_date
from ledgerai.services.statements.verify import (
    _INK_MIN_FRACTION,
    TokenCounts,
    _claimed_tokens,
    _ink_fraction,
    _within_budget,
)
from tests.synthetic_pdf import (
    DEFAULT_ROWS,
    STAMP,
    Run,
    summary_page,
    transaction_page,
    transposed_without_balance_statement,
    white_amount_statement,
    write_pdf,
)


def parse(data: bytes):
    return parse_statement(extract_pages(data))


class TestAmounts:
    @pytest.mark.parametrize(
        ("text", "cents"),
        [
            ("-42.10", -4210),
            ("42.10", 4210),
            ("(42.10)", -4210),
            ("42.10-", -4210),
            ("1,904.55", 190455),
            ("£1,234.56", 123456),
            ("42.10 CR", 4210),
            ("42.10 DR", -4210),
            ("−7.50", -750),
            ("+1800.00", 180000),
        ],
    )
    def test_printed_money_becomes_integer_cents(self, text: str, cents: int) -> None:
        assert parse_amount(text) == cents

    @pytest.mark.parametrize("text", ["", "abc", "4210", "12 Aug", "1.2.3", "42.1"])
    def test_things_that_are_not_money_are_refused(self, text: str) -> None:
        # A bare integer is the important one: a reference number is not an
        # amount, and treating it as one would invent transactions.
        assert parse_amount(text) is None

    def test_no_float_is_used(self) -> None:
        assert isinstance(parse_amount("0.10"), int)
        assert parse_amount("0.10") == 10


class TestDates:
    def test_a_full_date_needs_no_hint(self) -> None:
        assert parse_date("12/08/2026") == date(2026, 8, 12)
        assert parse_date("2026-08-12") == date(2026, 8, 12)

    def test_a_day_and_month_take_the_year_from_the_period(self) -> None:
        assert parse_date("12 Aug", year_hint=2026) == date(2026, 8, 12)
        assert parse_date("Aug 12", year_hint=2026) == date(2026, 8, 12)

    def test_a_day_and_month_without_a_hint_is_refused(self) -> None:
        # Guessing the current year would silently file a January statement
        # into the wrong year every January.
        assert parse_date("12 Aug") is None

    def test_an_impossible_date_is_refused(self) -> None:
        assert parse_date("31/02/2026") is None


